#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Copy the themes from this repository into the theme root ($DESKTOP_THEMES_ROOT/themes).
# Existing themes with other ids (your own snapshots) are never touched or deleted.
# Usage: scripts/install-themes.sh [--dry-run]
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
parse_common_flags "$@"

say "installing themes into $DT_ROOT/themes"
run mkdir -p "$DT_ROOT/themes"
for d in "$REPO"/themes/*/; do
  id=$(basename "$d")
  note "theme: $id"
  # -a keeps the relative symlinks used by macos-glass; gtk4/ of macos is generated by install-assets.sh
  # and must survive re-installation, so copy file by file instead of replacing the directory.
  run mkdir -p "$DT_ROOT/themes/$id"
  run cp -a "$d." "$DT_ROOT/themes/$id/"
done
