//! Generators: tokens → files (libadwaita CSS, GNOME Shell CSS, Ptyxis palette, wallpaper SVG)
//! and dconf keys. All output is a pure, deterministic function of the tokens and [`Target`].

pub mod gtk;
pub mod ptyxis;
pub mod settings;
pub mod shell;
pub mod wallpaper;

use std::path::PathBuf;

use crate::schema::Tokens;

/// Where and for which theme the output is produced, and what the theme's hand-made files
/// already provide (hand-made always wins).
#[derive(Clone, Debug, PartialEq)]
pub struct Target {
    pub theme_id: String,
    /// Theme NAME (palette name fallback).
    pub theme_name: String,
    /// Home directory, for `~` in `wallpaper.image`.
    pub home: String,
    /// The theme's cache directory (`~/.cache/desktop-themes/<id>`): generated wallpapers are
    /// referenced from dconf by absolute path.
    pub cache_dir: PathBuf,
    /// The theme (or a parent) ships its own `gtk4/` directory.
    pub handmade_gtk4: bool,
    /// The theme's dconf files set `user-theme name` themselves.
    pub handmade_shell_theme: bool,
}

/// Which artefacts the tokens produce for a target.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Outputs {
    pub gtk: bool,
    pub shell: bool,
    pub ptyxis: bool,
    pub wallpaper: bool,
}

impl Outputs {
    pub fn for_target(t: &Tokens, tg: &Target) -> Outputs {
        Outputs {
            gtk: !tg.handmade_gtk4 && t.has_gtk_content(),
            shell: !tg.handmade_shell_theme && t.shell_enabled(),
            ptyxis: t.terminal_palette().is_some(),
            wallpaper: t.wallpaper_svg(),
        }
    }
    pub fn any(&self) -> bool {
        self.gtk || self.shell || self.ptyxis || self.wallpaper
    }
}

pub const GTK4_DIR: &str = "gtk4";
pub const GTK_CSS: &str = "gtk4/gtk.css";
pub const SHELL_DIR: &str = "shell";
pub const SHELL_CSS: &str = "shell/gnome-shell/gnome-shell.css";
pub const WALLPAPER_LIGHT: &str = "wallpaper/light.svg";
pub const WALLPAPER_DARK: &str = "wallpaper/dark.svg";

/// Name under which the generated shell theme is installed (`~/.local/share/themes/<name>`).
pub fn shell_theme_name(theme_id: &str) -> String {
    format!("desktop-themes-{theme_id}")
}

/// Id of the generated Ptyxis palette (file `<id>.palette`).
pub fn ptyxis_palette_id(theme_id: &str) -> String {
    format!("desktop-themes-{theme_id}")
}

pub fn ptyxis_rel(theme_id: &str) -> String {
    format!("ptyxis/{}.palette", ptyxis_palette_id(theme_id))
}

/// A generated file, relative to the theme's cache directory.
#[derive(Clone, Debug, PartialEq)]
pub struct File {
    pub rel: String,
    pub contents: String,
}

pub fn header(comment_open: &str, comment_close: &str, theme_id: &str) -> String {
    format!(
        "{comment_open} Generated by desktop-themes-rs from themes/{theme_id}/tokens.toml. Do not edit: \
         change the tokens and apply the theme again. {comment_close}\n"
    )
}

/// Every file the tokens produce for the target.
pub fn render(t: &Tokens, tg: &Target) -> Vec<File> {
    let o = Outputs::for_target(t, tg);
    let mut v = Vec::new();
    if o.gtk {
        v.push(File {
            rel: GTK_CSS.into(),
            contents: gtk::css(t, &tg.theme_id),
        });
    }
    if o.shell {
        v.push(File {
            rel: SHELL_CSS.into(),
            contents: shell::css(t, &tg.theme_id),
        });
    }
    if o.ptyxis {
        v.push(File {
            rel: ptyxis_rel(&tg.theme_id),
            contents: ptyxis::palette(t, tg),
        });
    }
    if o.wallpaper {
        let (l, d) = wallpaper::svgs(t);
        v.push(File {
            rel: WALLPAPER_LIGHT.into(),
            contents: l,
        });
        v.push(File {
            rel: WALLPAPER_DARK.into(),
            contents: d,
        });
    }
    v
}

/// `1.5` → `1.5`, `2.0` → `2`.
pub(crate) fn num(v: f64) -> String {
    let s = format!("{v:.3}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s.is_empty() || s == "-0" { "0".into() } else { s.to_string() }
}
